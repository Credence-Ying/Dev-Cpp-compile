#include<stdio.h>

int main()
{
	int a;
	int *p;
	int c[3] = {1,3,5};
	unsigned long d[3] = {4,5,6};
	printf("%p\n", c); //输出的是c[0]的十六进制地址
	printf("%p\n",(c+1)); //输出的是c[1]的十六进制地址
	printf("%d\n", *(c+2)); //输出的是c[2]的值(因为用了*解指针)
	
	printf("%lu", d); //输出的是c[0]的地址,直接输出数组名就是输出数组第一位的地址
	/*
	数组名和指针的区别在于:数组名本质上是一个指针常量(不能修改),而定义的指针可以修改
	如不能 c = &a;  但是可以 *p = &a
	
	*/
	
	return 0;
	
}
