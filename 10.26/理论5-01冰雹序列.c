#include<stdio.h>

int n = 0;
int cnt = 0;

void hailstone(int k)
{
	printf("%4d",k);
	cnt++;
	while (k != 1)
	{
		if (k % 2 == 1) k = 3 * k + 1;
		else if (k % 2 == 0) k = k / 2;
		cnt++;
		printf("%4d", k);
		if (cnt % 6 == 0) putchar('\n');
	}
	if (cnt % 6 != 0) putchar('\n');
}

int main()
{
	scanf("%d", &n);
	printf("Hailstone generated by %d:\n", n);
	hailstone(n);
	printf("Number of hailstone generated: ");
	printf("%d", cnt);
	return 0;
}
